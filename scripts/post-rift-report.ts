async function main() {
  const only = process.argv[2]?.toLowerCase();
  const db = supabaseAdmin();
  const { data: users } = await db.auth.admin.listUsers({ perPage: 200 });
  const admin = users.users.find((u) => u.email === ADMIN_EMAIL);
  if (!admin) throw new Error(`관리자(${ADMIN_EMAIL}) 계정을 찾지 못했습니다.`);

  for (const r of REPORTS) {
    if (only && only !== r.key) continue;
    const { data: existing } = await db
      .from("posts")
      .select("id")
      .eq("category", "report")
      .eq("title", r.title)
      .maybeSingle();

    if (existing) {
      const { error } = await db
        .from("posts")
        .update({
          body: r.body,
          is_notice: true,
          is_pinned: true,
          updated_at: new Date().toISOString(),
        })
        .eq("id", existing.id);
      if (error) throw error;
      console.log(`갱신: ${r.title}`);
    } else {
      const { data, error } = await db
        .from("posts")
        .insert({
          category: "report",
          title: r.title,
          body: r.body,
          author_id: admin.id,
          is_notice: true,
          is_pinned: true,
        })
        .select("id")
        .single();
      if (error) throw error;
      console.log(`발행: ${r.title} → ${data.id}`);
    }
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
